// fileSection is one file's part of a diff, with one added line.
func fileSection(path, line string) string {
	return "diff --git a/" + path + " b/" + path + "\n" +
		"--- a/" + path + "\n" +
		"+++ b/" + path + "\n" +
		"@@ -0,0 +1 @@\n" +
		"+" + line + "\n"
}

func TestGeneratedFile(t *testing.T) {
	t.Parallel()

	assert.True(t, generated(fileSection("x.go", "// Code generated by stringer; DO NOT EDIT.")))
	assert.True(t, generated(fileSection("x.py", "# Code generated by tool. DO NOT EDIT.")))
	assert.True(t, generated(fileSection("x.js", " * @generated")))
	assert.True(t, generated(fileSection("x.js", "// @generated by relay")))
	// The marker as context in a hunk of a file changed later.
	assert.True(t, generated("diff --git a/x.go b/x.go\n--- a/x.go\n+++ b/x.go\n@@ -1,2 +1,2 @@\n // Code generated by mockgen. DO NOT EDIT.\n-a\n+b\n"))

	assert.False(t, generated(fileSection("x.go", "x := 1")))
	// Code that only mentions the markers, like Bark's own.
	assert.False(t, generated(fileSection("x.go", `re := regexp.MustCompile("Code generated .* DO NOT EDIT")`)))
	assert.False(t, generated(fileSection("x.go", `if strings.Contains(s, "@generated") {`)))
	// A removed marker: the new file isn't generated any more.
	assert.False(t, generated("diff --git a/x.go b/x.go\n--- a/x.go\n+++ b/x.go\n@@ -1 +1 @@\n-// Code generated by x. DO NOT EDIT.\n+package x\n"))
}

func TestSectionPath(t *testing.T) {
	t.Parallel()

	assert.Equal(t, "dir/a b.go", sectionPath(fileSection("dir/a b.go", "x")))
	// Git adds a tab after a path with a space.
	assert.Equal(t, "d/a b.go", sectionPath("diff --git a/d/a b.go b/d/a b.go\nnew file mode 100644\n--- /dev/null\n+++ b/d/a b.go\t\n@@ -0,0 +1 @@\n+x\n"))
	assert.Equal(t, "gone.go", sectionPath("diff --git a/gone.go b/gone.go\ndeleted file mode 100644\n--- a/gone.go\n+++ /dev/null\n@@ -1 +0,0 @@\n-x\n"))
	assert.Equal(t, "img.png", sectionPath("diff --git a/img.png b/img.png\nnew file mode 100644\nBinary files /dev/null and b/img.png differ\n"))
	assert.Equal(t, "new.go", sectionPath("diff --git a/old.go b/new.go\nsimilarity index 100%\nrename from old.go\nrename to new.go\n"))
	assert.Equal(t, "café.go", sectionPath("diff --git \"a/caf\\303\\251.go\" \"b/caf\\303\\251.go\"\n--- \"a/caf\\303\\251.go\"\n+++ \"b/caf\\303\\251.go\"\n@@ -0,0 +1 @@\n+x\n"))
	assert.Empty(t, sectionPath("diff --git a\n+1\n"))
}

// A diff over its limit keeps code first, then tests, docs, fixtures and
// generated files, whatever order the diff has them in.
func TestTruncateDiffRanksFiles(t *testing.T) {
	t.Parallel()

	readme := fileSection("README.md", "docs")
	test := fileSection("a_test.go", "test")
	code := fileSection("core.go", "code")
	gen := fileSection("b_gen.go", "// Code generated by x. DO NOT EDIT.")
	fixture := fileSection("testdata/in.txt", "fixture")
	diff := gen + fixture + readme + test + code // five lines a file

	t.Run("fits: unchanged", func(t *testing.T) {
		t.Parallel()
		got, cut := truncateDiff(diff, DiffLimit{Lines: 25})
		assert.Equal(t, diff, got)
		assert.Nil(t, cut)
	})

	t.Run("cut at a file boundary", func(t *testing.T) {
		t.Parallel()
		got, cut := truncateDiff(diff, DiffLimit{Lines: 10})
		assert.Equal(t, code+test+truncatedMarker, got)
		assert.Equal(t, &DiffCut{Files: 5, Kept: 2, Setting: "max_diff_lines", Dropped: []string{"README.md", "testdata/in.txt", "b_gen.go"}}, cut)
	})

	t.Run("cut inside a file", func(t *testing.T) {
		t.Parallel()
		got, cut := truncateDiff(diff, DiffLimit{Tokens: uint32(float64(len(code)+len(test)+len(readme)-3) / tokens.CharsPerToken)})
		assert.True(t, strings.HasPrefix(got, code+test+"diff --git a/README.md"), got)
		assert.Equal(t, &DiffCut{Files: 5, Kept: 3, Partial: true, PartialFile: "README.md", Setting: "max_diff_tokens", Dropped: []string{"testdata/in.txt", "b_gen.go"}}, cut)
	})

	t.Run("a commit's message stays first", func(t *testing.T) {
		t.Parallel()
		head := "commit abc\nAuthor: A <a@b>\n\n    subject\n\n"
		got, cut := truncateDiff(head+test+code, DiffLimit{Lines: 10})
		assert.Equal(t, head+code+truncatedMarker, got)
		assert.Equal(t, &DiffCut{Files: 2, Kept: 1, Setting: "max_diff_lines", Dropped: []string{"a_test.go"}}, cut)
	})
}

func TestDiffCutSummaryNamesFiles(t *testing.T) {
	t.Parallel()

	assert.Equal(t, "Bark reviewed only 2 of 5 changed files, `b.go` in part: the diff was cut to fit max_diff_tokens, code first and tests, docs, fixtures and generated files last. Left out: `c_test.go`, `README.md` and `gen.go`.",
		DiffCut{Files: 5, Kept: 2, Partial: true, PartialFile: "b.go", Setting: "max_diff_tokens", Dropped: []string{"c_test.go", "README.md", "gen.go"}}.Summary())
	assert.Equal(t, "Bark reviewed only 1 of 2 changed files: the diff was cut to fit max_diff_lines, code first and tests, docs, fixtures and generated files last. Left out: `a_test.go`.",
		DiffCut{Files: 2, Kept: 1, Setting: "max_diff_lines", Dropped: []string{"a_test.go"}}.Summary())

	var many []string
	for _, c := range "abcdefghijklm" {
		many = append(many, string(c)+".md")
	}
	got := DiffCut{Files: 14, Kept: 1, Setting: "max_diff_tokens", Dropped: many}.Summary()
	assert.True(t, strings.HasSuffix(got, " Left out: `a.md`, `b.md`, `c.md`, `d.md`, `e.md`, `f.md`, `g.md`, `h.md`, `i.md`, `j.md` and 3 more."), got)
}

// Every source ranks the files the same way: a branch's diff (read from
// git) and a commit's (which starts with its message).
func TestGetReviewDiffRanksFiles(t *testing.T) {
	dir := newDivergedRepo(t)
	big := strings.Repeat("a line of the big test\n", 100)
	require.NoError(t, os.WriteFile(filepath.Join(dir, "a_test.go"), []byte(big), 0o644))
	require.NoError(t, os.WriteFile(filepath.Join(dir, "z.go"), []byte("package z\n"), 0o644))
	runGit(t, dir, "add", "a_test.go", "z.go")
	runGit(t, dir, "commit", "-m", "add a test and z")

	check := func(t *testing.T, params ReviewDiffParams, files int) {
		t.Helper()
		full, err := GetReviewDiff(t.Context(), params)
		require.NoError(t, err)
		require.Nil(t, full.Cut)
		test := strings.Index(full.Diff, "diff --git a/a_test.go")
		require.GreaterOrEqual(t, test, 0)

		// Room for everything but the end of the test.
		limit := DiffLimit{Tokens: uint32(float64(len(full.Diff)-200) / tokens.CharsPerToken)}
		r, err := GetReviewDiff(t.Context(), params.WithLimit(limit))
		require.NoError(t, err)
		assert.Equal(t, &DiffCut{Files: files, Kept: files, Partial: true, PartialFile: "a_test.go", Setting: "max_diff_tokens"}, r.Cut)
		assert.Less(t, strings.Index(r.Diff, "diff --git a/z.go"), strings.Index(r.Diff, "diff --git a/a_test.go"), "code before tests")
		assert.Equal(t, full.Diff[:test], r.Diff[:test], "what comes before the first file stays first")
	}

	t.Run("branch", func(t *testing.T) { check(t, BranchDiff("main"), 3) })
	t.Run("commit", func(t *testing.T) { check(t, CommitDiff("HEAD"), 2) })
}
